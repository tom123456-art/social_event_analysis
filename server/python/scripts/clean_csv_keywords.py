def clean(text):
    return re.sub(r"\s+", " ", re.sub(r"<[^>]*>", " ", html.unescape(text or ""))).strip()

def frequent_sentences(rows):
    counts = Counter()
    for row in rows:
        counts.update(set(s.strip() for s in re.split(r"[。！？!?\n]", clean(row.get("content_text", ""))) if len(s.strip()) >= 18))
    return {sentence for sentence, count in counts.items() if count >= 15}

def meaningful_body(row, repeated):
    title = clean(row.get("title", ""))
    parts = re.split(r"[。！？!?\n]", clean(row.get("content_text", "")))
    return "。".join(s for s in parts if len(s.strip()) >= 8 and s.strip() not in repeated
                    and not TEMPLATE.search(s) and s.strip() != title)[:1200]

def matches(text):
    return [(pattern, terms) for pattern, terms in COMPILED if pattern.search(text)]

def keywords(row, repeated=frozenset()):
    platform = row.get("platform", "").strip().upper()
    if platform not in NEWS:
        return [], "weibo" if platform in WEIBO else "unknown_platform"
    title = clean(row.get("title", ""))
    if not title or not re.search(r"[\u3400-\u9fffA-Za-z0-9]", title) or title.count("\ufffd") > len(title) / 5:
        return [], "unreadable_title"
    title_matches = matches(title)
    if row.get("category", "").strip() in {"体育", "sports"} and re.search(r"\d\s*[-：:]\s*\d", title):
        title_matches.insert(0, (None, ("比赛结果", "竞技赛事")))
    body = meaningful_body(row, repeated)
    # The title anchors the topic. Body-only concepts cannot displace it.
    body_matches = matches(body)
    supported = {term for _, terms in title_matches for term in terms}
    exact = sorted((term for term in EXACT_TOPICS if term.lower() in title.lower()),
                   key=lambda term: (-len(term), title.lower().index(term.lower()), term))
    # Prefer a specific phrase to a substring of the same phrase.
    selected = []
    for term in exact:
        if not any(term.lower() in chosen.lower() for chosen in selected):
            selected.append(term)
    original = SPLIT.split(row.get("keywords", ""))
    for term in original:
        if term in supported and term in title and term not in selected:
            selected.append(term)
    for _, terms in title_matches:
        for term in terms:
            if term not in selected:
                selected.append(term)
    if not selected:
        for _, terms in body_matches:
            for term in terms:
                if term not in selected:
                    selected.append(term)
    return selected[:3], "topic_rules" if selected else "insufficient_evidence"

def digest(path):
    with path.open("rb") as handle:
        return hashlib.file_digest(handle, "sha256").hexdigest()

def read_csv(path):
    with path.open(encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        fields = reader.fieldnames
        if not fields or "keywords" not in fields:
            raise ValueError(f"Missing keywords column: {path}")
        rows = list(reader)
    if any(None in row or any(value is None for value in row.values()) for row in rows):
        raise ValueError(f"Malformed CSV: {path}")
    return fields, rows

def process(source, run_dir, apply=False):
    source = source.resolve()
    folder = run_dir / source.parent.name
    folder.mkdir(parents=True, exist_ok=False)
    snapshot = folder / "original.csv"
    shutil.copy2(source, snapshot)
    original_hash = digest(snapshot)
    fields, rows = read_csv(snapshot)
    repeated = frequent_sentences(rows)
    counts, platforms, frequency = Counter(), {}, Counter()
    output = folder / "cleaned.csv"
    audit = folder / "changes.jsonl"
    with output.open("w", encoding="utf-8-sig", newline="") as handle, audit.open("w", encoding="utf-8") as log:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        for index, row in enumerate(rows):
            terms, reason = keywords(row, repeated)
            new = ",".join(terms)
            platform = row["platform"].strip().upper()
            platforms.setdefault(platform, Counter()).update({"rows": 1, "keywords": len(terms), f"count_{len(terms)}": 1})
            counts["rows"] += 1
            counts["changed"] += row["keywords"] != new
            counts[reason] += 1
            frequency.update(terms)
            log.write(json.dumps({"row": index + 2, "content_id": row.get("content_id"), "platform": platform,
                                  "title": row.get("title"), "before": row["keywords"], "after": new,
                                  "reason": reason}, ensure_ascii=False) + "\n")
            writer.writerow({**row, "keywords": new})
    after_fields, after_rows = read_csv(output)
    assert fields == after_fields and len(rows) == len(after_rows)
    for before, after in zip(rows, after_rows):
        assert all(before[key] == after[key] for key in fields if key != "keywords")
        terms = [x for x in after["keywords"].split(",") if x]
        assert len(terms) <= 3 and set(terms) <= VOCABULARY
        assert after["platform"].strip().upper() in NEWS or not terms
    summary = {"source": str(source), "original_sha256": original_hash, "counts": dict(counts),
               "platforms": platforms, "top30": frequency.most_common(30), "applied": apply}
    if apply:
        if digest(source) != original_hash:
            raise RuntimeError("CSV changed during review; refusing to overwrite")
        staging = source.with_suffix(".keywords.tmp")
        shutil.copyfile(output, staging)
        staging.replace(source)
        assert digest(source) == digest(output)
    (folder / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(summary, ensure_ascii=False, indent=2), flush=True)
    return summary

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv", nargs="+", type=Path)
    parser.add_argument("--run-dir", type=Path, default=Path("runtime/keyword-cleanup") / datetime.now().strftime("%Y%m%d-%H%M%S"))
    parser.add_argument("--apply", action="store_true")
    args = parser.parse_args()
    for source in args.csv:
        process(source, args.run_dir, args.apply)

if __name__ == "__main__":
    main()
